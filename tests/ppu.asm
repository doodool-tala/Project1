    ST 0x9800,0x00
    ST 0x9801,0x01
    ST 0x9802,0x02
    ST 0x9820,0x80
    ; window map at 0x9C00
    ST 0x9C00,0x02
    ST 0x9C01,0x00
    ST 0x9C02,0x02
    ST 0x9C20,0x01
    ; palettes
    ST 0xFF47,0xE4
    ST 0xFF48,0xE4
