    ST 0x901D,0x00
    ST 0x901E,0xFF
    ST 0x901F,0x00
    ; tile 2 at 0x9020: left half color 1, right half color 2
    ST 0x9020,0xF0
    ST 0x9021,0x0F
    ST 0x9022,0xF0
    ST 0x9023,0x0F
    ST 0x9024,0xF0
    ST 0x9025,0x0F
