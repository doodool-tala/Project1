    ST 0x900B,0x18
    ST 0x900C,0x24
    ST 0x900D,0x24
    ST 0x900E,0x42
    ST 0x900F,0x42
    ; tile 1 at 0x9010: solid color 1
    ST 0x9010,0xFF
    ST 0x9011,0x00
    ST 0x9012,0xFF
    ST 0x9013,0x00
    ST 0x9014,0xFF
    ST 0x9015,0x00
