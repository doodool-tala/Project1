    DI
    LDSP 0xFFFE
    LDA 0x00
    LDH_A 0x40                 ; LCD off
    ; tile 0 at 0x9000: asymmetric rows
    ST 0x9000,0xFF
    ST 0x9001,0x00
    ST 0x9002,0x00
    ST 0x9003,0xFF
    ST 0x9004,0xAA
