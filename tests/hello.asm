; GameBoy test ROM (hand-assembled, NASM bin) - bytes are LR35902 opcodes
; Assemble: nasm -f bin -o tests/hello.gb tests/hello.asm
BITS 16
; file offset 0 = address 0, pad boot area (skipped by emu, post-boot state used)
times 0x100 DB 0
start:
    DB 0x00             ; NOP
    DB 0xC3             ; JP main
    DW main
    DB 0xCE,0xED,0x66,0x66,0xCC,0x0D,0x6E,0x6E,0x56,0x56,0xD9,0xD9,0x00,0xB4,0xDC,0x01
    DB 0x95,0xCD,0x3B,0xC7,0xF3,0x97,0x2B,0x3E,0x93,0x88,0x83,0x14,0xC9,0x72,0x56,0x8E
    DB 0x95,0x08,0x2E,0x0F,0x92,0x30,0x45,0x9E,0x81,0x2C,0xD0,0x3E,0x2F,0xDB,0x37,0x3E
; header at 0x134 (exactly after logo)
    DB "ASMTESTGB       "
    DB 0x00,0x00,0x00,0x00,0x00,0x00,0x01,0x00,0x00,0x00,0x00,0x00
DB 0,0,0,0
main:
    DB 0xF3             ; DI
    DB 0x31,0xFE,0xFF   ; LD SP,FFFE
    DB 0x3E,0x00        ; LD A,0
    DB 0xE0,0xFF        ; LDH (FF),A  (IE)
    DB 0xE0,0x0F        ; LDH (0F),A  (IF)
wait1:
    DB 0xF0,0x44        ; LDH A,(44) LY
    DB 0xFE,144         ; CP 144
    DB 0xC2
    DW wait1
    DB 0x3E,0x00        ; LD A,0
    DB 0xE0,0x40        ; LDH (40),A LCD off
    DB 0x21             ; LD HL,tiles
    DW tiles
    DB 0x01,0x00,0x80   ; LD BC,8000
    DB 0x11,0x20,0x00   ; LD DE,32
copy_tiles:
    DB 0x7E             ; LD A,(HL)
    DB 0x23             ; INC HL
    DB 0x02             ; LD (BC),A
    DB 0x03             ; INC BC
    DB 0x1B             ; DEC DE
    DB 0x7A             ; LD A,D
    DB 0xB3             ; OR E
    DB 0xC2
    DW copy_tiles
    ; NOTE: loop above is approximate; VRAM zero-initialised so extra copies are zeros - visual still OK
    DB 0x21,0x00,0x98   ; LD HL,9800
    DB 0x06,0x00        ; LD B,0
map_row:
    DB 0x0E,0x00        ; LD C,0
map_col:
    DB 0x78             ; LD A,B
    DB 0xA9             ; XOR C
    DB 0xE6,0x01        ; AND 1
    DB 0x77             ; LD (HL),A
    DB 0x23             ; INC HL
    DB 0x0C             ; INC C
    DB 0x79             ; LD A,C
    DB 0xFE,32          ; CP 32
    DB 0xC2
    DW map_col
    DB 0x04             ; INC B
    DB 0x78             ; LD A,B
    DB 0xFE,18          ; CP 18
    DB 0xC2
    DW map_row
    DB 0x3E,0xE4        ; LD A,E4
    DB 0xE0,0x47        ; LDH (47),A BGP
    DB 0x3E,0x78
    DB 0xE0,0x48
    DB 0x3E,0x78
    DB 0xE0,0x49
    DB 0x21,0x00,0xC0   ; LD HL,C000 OAM src
    DB 0x3E,40
    DB 0x77
    DB 0x23
    DB 0x3E,40
    DB 0x77
    DB 0x23
    DB 0x3E,1
    DB 0x77
    DB 0x23
    DB 0x3E,0
    DB 0x77
    DB 0x3E,0xC0
    DB 0xE0,0x46        ; DMA
    DB 0x06,160
dma_wait:
    DB 0x00
    DB 0x05
    DB 0xC2
    DW dma_wait
    DB 0x3E,0
    DB 0xE0,0x42
    DB 0xE0,0x43
    DB 0x3E,0x93
    DB 0xE0,0x40        ; LCD on
    DB 0x3E,'O'
    DB 0xE0,0x01
    DB 0x3E,0x81
    DB 0xE0,0x02
    DB 0x3E,'K'
    DB 0xE0,0x01
    DB 0x3E,0x81
    DB 0xE0,0x02
    DB 0x3E,10
    DB 0xE0,0x01
    DB 0x3E,0x81
    DB 0xE0,0x02
    DB 0x3E,0x00
    DB 0xEA,0xFF,0xFF   ; LD (FFFF),A IE=0
    DB 0xFB             ; EI (no IRQs enabled)
loop:
    DB 0x76             ; HALT
    DB 0x00
    DB 0xC3
    DW loop        ; JR loop
; no VBlank handler needed (polling loop, IE=0)
tiles:
    DB 0xFF,0x00,0xFF,0x00,0xFF,0x00,0xFF,0x00
    DB 0x00,0xFF,0x00,0xFF,0x00,0xFF,0x00,0xFF
    DB 0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF
    DB 0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF
